namespace CDC.Api.Domain.Entities;

/// <summary>One review comment (or reply) for a profile version section, read from the recursive
/// <c>spgReviewCommentByProfileVersionSection</c> query.</summary>
public sealed record ProfileReviewComment
{
    /// <summary>Gets the comment identifier.</summary>
    public Guid Id { get; init; }

    /// <summary>Gets the date the comment was made.</summary>
    public DateTime CommentDate { get; init; }

    /// <summary>Gets the comment's subject line.</summary>
    public string CommentSubject { get; init; } = string.Empty;

    /// <summary>Gets the comment's optional reference text.</summary>
    public string CommentReference { get; init; } = string.Empty;

    /// <summary>Gets the comment's body text.</summary>
    public string CommentText { get; init; } = string.Empty;

    /// <summary>Gets the commenting user's logon name.</summary>
    public string UserName { get; init; } = string.Empty;

    /// <summary>Gets the commenting user's full name.</summary>
    public string UserFullName { get; init; } = string.Empty;

    /// <summary>Gets the parent comment this is a reply to, or <see cref="Guid.Empty"/> for a
    /// top-level comment.</summary>
    public Guid ParentId { get; init; }

    /// <summary>Gets the thread depth: 1 for a top-level comment, 2 for a reply, and so on.</summary>
    public int Level { get; init; }

    /// <summary>Gets the number of direct replies to this comment.</summary>
    public int ChildCount { get; init; }

    /// <summary>Gets the comment's row version.</summary>
    public byte[] LastUpdated { get; init; } = [];
}

/// <summary>The values needed to insert a review comment via <c>spiReviewComment</c>.</summary>
public sealed record NewProfileReviewComment
{
    /// <summary>Gets the new comment's identifier (generated by the caller).</summary>
    public required Guid Id { get; init; }

    /// <summary>Gets the profile version being commented on.</summary>
    public required Guid ProfileVersionId { get; init; }

    /// <summary>Gets the section being commented on.</summary>
    public required Guid ProfileSectionId { get; init; }

    /// <summary>Gets the parent comment when this is a reply, otherwise <see langword="null"/>.</summary>
    public Guid? ParentId { get; init; }

    /// <summary>Gets the time the comment was made.</summary>
    public required DateTime CommentDate { get; init; }

    /// <summary>Gets the subject line.</summary>
    public required string Subject { get; init; }

    /// <summary>Gets the reference text.</summary>
    public required string CommentReference { get; init; }

    /// <summary>Gets the comment body.</summary>
    public required string CommentText { get; init; }

    /// <summary>Gets the commenting user's logon name (the procedure resolves the user from it).</summary>
    public required string UserName { get; init; }
}

/// <summary>The acting user's identity as needed to author and own review comments.</summary>
public sealed record ReviewCommentUser
{
    /// <summary>Gets the user's logon name.</summary>
    public required string UserName { get; init; }

    /// <summary>Gets the user's full name.</summary>
    public required string FullName { get; init; }
}
