using CDC.Common.Contracts;
using CDC.Web.Models;

namespace CDC.Web.Infrastructure.Reports;

/// <summary>
/// Lays out the summary prioritisation report (SPR) guidance report for printing, matching the legacy
/// <c>SummaryPrioritisationGuidanceReportPdf</c>: the standard text that explains D2R2 scoring, the guidance for the ten
/// questions the SPR prints, then the guidance behind each scoring criterion, grouped and coloured by category.
/// The questions listed here must match those in the summary prioritisation report.
/// </summary>
public static class SprGuidanceReportLayout
{
    /// <summary>The category whose first criterion depends on the disease being endemic or exotic.</summary>
    public static readonly Guid EndemicOrExoticCategoryId = new("CC99BFDF-6621-4390-84D6-91218A40DF1D");

    /// <summary>The question whose guidance is followed by that of the exotic question, which shares its criterion code and so is not listed.</summary>
    public static readonly Guid EndemicQuestionId = new("745A30C4-5098-4D02-91B2-55E75F54551F");

    private const string CriteriaTitle = "Detailed criteria scores";

    private static readonly (string Heading, int Section, int Question)[] Questions =
    [
        ("Summary description", 1, 1),
        ("RFI 1 Protect human health", 6, 14),
        ("RFI 2 Protect and promote animal welfare", 5, 9),
        ("RFI 3 Protect interests of wider economy, environment & society", 7, 7),
        ("RFI 4 International trade", 13, 11),
        ("Post mitigation risk", 3, 20),
        ("Public perception", 15, 1),
        ("Summary of central government veterinary expenditure", 7, 8),
        ("Uncertainty", 16, 1),
        ("Legislation", 8, 4)
    ];

    private static readonly string[][] ExampleRows =
    [
        ["Total unplanned cost to exchequer", "Negligible / Low / Medium / High / Very High", "0", "25", "10", "0", "250"],
        ["Impact on the global environment", "Negligible / Some", "0", "25", "1", "0", "25"],
        ["Impact on the local environment", "Negligible / Low / Medium", "0", "25", "9", "0", "225"],
        ["Impact on the sector that produces this species", "Negligible / Low / Medium / High / Very High", "0", "25", "5", "0", "125"],
        ["Impact on the wider rural community", "Negligible / Low / Medium / High / Very High", "0", "25", "10", "0", "250"]
    ];

    /// <summary>The column headings of the worked example's table.</summary>
    public static readonly IReadOnlyList<string> ExampleHeadings =
    [
        "Question / Criterion Title",
        "Scoring (Category) Options",
        "Lowest Possible Score",
        "Highest Possible Score",
        "Weighting",
        "Weighted Lowest Possible Score",
        "Weighted Highest Possible Score"
    ];

    /// <summary>Lays out the report.</summary>
    /// <param name="content">The sections, questions, guidance and prioritisation criteria.</param>
    /// <returns>The laid-out report.</returns>
    /// <exception cref="InvalidOperationException">A question the report prints is not in <paramref name="content"/>.</exception>
    public static SprGuidanceReportViewModel Build(ProfileGuidanceContentDto content)
    {
        ArgumentNullException.ThrowIfNull(content);

        var questionsById = content.Sections.SelectMany(section => section.Questions).ToDictionary(question => question.Id);

        return new SprGuidanceReportViewModel(
            GuidanceReportLayout.SprTitle,
            BuildStandardText(),
            [.. ExampleRows.Select(cells => new SprExampleRowView(cells))],
            "Overall maximum score for this reason for Government intervention (RFI) =",
            "875",
            "This total is then used as a denominator so that the scores generated by the categories selected for each disease for Wider society are divided by 875 and " +
            "multiplied by 100 to give an overall score out of 100. Other RFIs have different numbers of criteria and different weights, but all report a percentage score.",
            [.. Questions.Select(entry => new SprQuestionView(entry.Heading, GuidanceReportLayout.FindQuestion(content, entry.Section, entry.Question).UserGuidance))],
            CriteriaTitle,
            [.. content.PrioritisationCategories.Select(category => BuildCategory(content, questionsById, category))]);
    }

    /// <summary>Gets the background colour the legacy report gave a category.</summary>
    /// <param name="categoryName">The category's display name.</param>
    /// <returns>A CSS colour.</returns>
    public static string BackgroundColourOf(string categoryName) => categoryName.ToLowerInvariant() switch
    {
        "international trade" => "rgb(255,255,189)",
        "wider society" => "rgb(153,204,255)",
        "welfare" => "rgb(193,255,193)",
        "public health" => "rgb(255,153,204)",
        "post mitigation risk" => "rgb(0,0,0)",
        _ => "rgb(0,163,59)"
    };

    /// <summary>Gets the text colour the legacy report gave a category: white on the black post mitigation risk, otherwise black.</summary>
    /// <param name="categoryName">The category's display name.</param>
    /// <returns>A CSS colour.</returns>
    public static string ForegroundColourOf(string categoryName) =>
        string.Equals(categoryName, "post mitigation risk", StringComparison.OrdinalIgnoreCase) ? "rgb(255,255,255)" : "rgb(0,0,0)";

    private static SprCategoryView BuildCategory(
        ProfileGuidanceContentDto content,
        Dictionary<Guid, ProfileGuidanceQuestionDto> questionsById,
        PrioritisationGuidanceCategoryDto category) => new(
            category.DisplayName,
            category.Id == EndemicOrExoticCategoryId ? GuidanceReportLayout.EndemicOrExoticNote : null,
            BackgroundColourOf(category.DisplayName),
            ForegroundColourOf(category.DisplayName),
            [.. category.Criteria.Select(criterion => BuildCriterion(content, questionsById, criterion))]);

    private static SprCriterionView BuildCriterion(
        ProfileGuidanceContentDto content,
        Dictionary<Guid, ProfileGuidanceQuestionDto> questionsById,
        PrioritisationGuidanceCriterionDto criterion)
    {
        if (!questionsById.TryGetValue(criterion.ProfileQuestionId, out var question))
        {
            throw new InvalidOperationException($"Could not find profile question with ID '{criterion.ProfileQuestionId}'.");
        }

        var guidance = new List<string> { question.UserGuidance };

        // The exotic question shares the endemic question's criterion code, so only the endemic one is listed; its guidance follows.
        if (criterion.ProfileQuestionId == EndemicQuestionId)
        {
            guidance.Add(GuidanceReportLayout.FindQuestion(content, 2, 4).UserGuidance);
        }

        return new SprCriterionView(criterion.CriterionName, guidance);
    }

    private static SprStandardSectionView[] BuildStandardText() =>
    [
        new("D2R2 Scoring: Overall Approach",
            [
                Paragraph(
