                Paragraph(
                    "The fifth area for which a score is " +
                    "generated is termed the post-mitigation risk (PMR). This relates to how well current control measures (both controls arising from legal " +
                    "requirement and those generally undertaken by animal keepers as part of effective management) can mitigate the impact of the specific disease. " +
                    "It is colour-coded black on D2R2 outputs. " +
                    "For exotic diseases all scores, including that for post-mitigation risk, consider the most likely disease incursion and the control measures " +
                    "it is anticipated will be pursued.")
            ],
            false,
            []),
        new("How A D2R2 Score Is Generated",
            [
                Paragraph(
                    "Each of these five areas of interest includes a number of scoring criteria. Each of these can have up to seven categorical options " +
                    "(the specific categories used for each scoring question ('criterion') are described below), " +
                    "wherever possible underpinned by quantitative ranges. Each option is clearly set out in the guidance on that question provided to the " +
                    "authors and also available later in this report. Each of the categorical options available for each scoring question ('criterion') in D2R2 are described " +
                    "to the authors in text, e.g. ‘low’, but each scoring option is assigned a numerical value between 0 or 1 and 25 by the analytical module.")
