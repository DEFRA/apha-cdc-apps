                    "in the category selected for that criterion will change the disease’s overall score and therefore its relative ranking."),
                Paragraph(
                    "The result of using the weightings included in the example table above on the overall " +
                    "Wider society score is that the final score (which is out of 100) describes:"),
                Bullet("Risk of unexpected government costs 29%"),
                Bullet("Wider community social and economic impact 29%"),
                Bullet("Environmental impact 29%"),
                Bullet("Producer economic impact 14%")
            ]),
        new("Why D2R2 Disease Scores Are Used To Create Rankings And How To Interpret The Rankings",
            [
                Paragraph(
                    "D2R2 calculates scores for each section separately and makes no assumption about the relative importance of the five substantive sections. " +
                    "However as the highest ranked diseases for the four different reasons for Government intervention have numerically different scores that have " +
                    "no intrinsic meaning, comparative outputs from D2R2 are presented as ranked positions, to avoid implying that one RFI is more important than another. " +
                    "For the post-mitigation risk score a low figure represents a well-controlled disease, a high number a poorly-controlled disease. For a disease " +
                    "with a numerically large score that therefore appears high in the rankings table for one or more of the reasons for Government intervention the " +
