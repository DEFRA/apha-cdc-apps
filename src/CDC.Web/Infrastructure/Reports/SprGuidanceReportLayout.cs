                    "The values for each criterion within each section are summed to give an initial overall summary score that describes that disease’s impact on the " +
                    "specific RFI or in terms of the post-mitigation risk. D2R2 transforms each of the five overall scores generated for each disease into a percentage " +
                    "derived from a scale generated by allocating ‘0’ for the value generated by summing the lowest value possible for each criterion, and ‘100’ for that " +
