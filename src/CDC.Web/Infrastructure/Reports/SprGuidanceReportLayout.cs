                    "Scoring within D2R2 is additive for each of five separate areas of interest. The relative priority of animal diseases " +
                    "is assessed in the context of the four ‘reasons for government intervention’ (RFI) defined by the GB Animal Health and Welfare Strategy " +
                    "(AHWS, published in 2004). These are:"),
                Bullet("'to protect public health' (colour-coded pink on D2R2 outputs)"),
                Bullet("'to protect and promote the welfare of animals' (colour-coded green on D2R2 outputs)"),
